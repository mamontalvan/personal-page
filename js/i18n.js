const STORAGE_KEY = "portfolio-lang";
const SUPPORTED = ["es", "en"];

const detectLanguage = () => {
  const params = new URLSearchParams(window.location.search);
  const fromQuery = params.get("lang");
  if (SUPPORTED.includes(fromQuery)) return fromQuery;

  const stored = localStorage.getItem(STORAGE_KEY);
  if (SUPPORTED.includes(stored)) return stored;

  const browser = (navigator.language || "es").slice(0, 2).toLowerCase();
  return SUPPORTED.includes(browser) ? browser : "es";
};

const applyLanguage = (lang) => {
  const dict = translations[lang];
  if (!dict) return;

  document.documentElement.lang = lang;
  document.title = dict["meta.title"];

  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", dict["meta.desc"]);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = dict[el.getAttribute("data-i18n")];
    if (value != null) el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const value = dict[el.getAttribute("data-i18n-html")];
    if (value != null) el.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = dict[el.getAttribute("data-i18n-aria")];
    if (value != null) el.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const value = dict[el.getAttribute("data-i18n-alt")];
    if (value != null) el.setAttribute("alt", value);
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.setAttribute("aria-pressed", String(active));
    btn.classList.toggle("is-active", active);
  });
};

const setLanguage = (lang) => {
  if (!SUPPORTED.includes(lang)) return;
  localStorage.setItem(STORAGE_KEY, lang);
  const url = new URL(window.location.href);
  url.searchParams.set("lang", lang);
  window.history.replaceState({}, "", url);
  applyLanguage(lang);
};

const initI18n = () => {
  applyLanguage(detectLanguage());

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });
};

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initI18n);
} else {
  initI18n();
}
